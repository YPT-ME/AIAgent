"""
RAG AI Agent - Document Loaders

This module provides document loading functionality using LlamaIndex
for parsing PDF and Markdown files with metadata.
"""

import logging
import os
import re
from pathlib import Path
from urllib.parse import quote

from llama_index.core import Document

from src.ingestion.markdown import markdown_lines

logger = logging.getLogger(__name__)

# Supported file extensions
SUPPORTED_EXTENSIONS = {".pdf", ".md", ".markdown"}

# GitHub Wiki resolves pages by their unique file name, whatever subfolder the file is in
WIKI_BASE_URL = os.getenv("WIKI_BASE_URL", "https://github.com/WWBN/AVideo/wiki/")

# GitHub Wiki navigation fragments, not documentation pages
WIKI_SPECIAL_PAGES = {"_Sidebar", "_Footer", "_Header"}

GENERATED_MARKER = "<!-- Generated by"

# Relative wiki links such as [Live](Live-Plugin) or [x](Page-(Note)#anchor); images are skipped
_RELATIVE_WIKI_LINK = re.compile(r"(?<!!)\]\((?!https?:|mailto:|#|/)((?:[^()\s/]|\([^()\s/]*\))+)\)")
_H1 = re.compile(r"^#\s+(.+?)\s*#*\s*$", re.MULTILINE)
_AUDIENCE = re.compile(r"^Audience:\s*([^\n]+?)\.(?:\s|$)", re.MULTILINE)
_REVIEW_DATE = re.compile(r"(?:Review date|Baseline reviewed):\s*(\d{4}-\d{2}-\d{2})")
_PLUGIN_VERSION = re.compile(r"^- Reported version:\s*`([^`]+)`", re.MULTILINE)
_CODE_OWNERSHIP = re.compile(r"^- Code ownership:\s*(.+?)\.?\s*$", re.MULTILINE)


def is_indexable(file_path: Path) -> bool:
    """Supported documentation file that is not a wiki navigation fragment."""
    return file_path.suffix.lower() in SUPPORTED_EXTENSIONS and file_path.stem not in WIKI_SPECIAL_PAGES


def wiki_url(page_name: str) -> str:
    """Public GitHub Wiki URL of a page (file name without extension)."""
    return WIKI_BASE_URL + quote(page_name, safe="-_.~")


def doc_category(page_name: str) -> str:
    """Kind of wiki page, so basic guides, explanations and symbol inventories can be told apart."""
    if page_name.startswith("Technical-Reference-") and page_name != "Technical-Reference-Index":
        return "technical_inventory"
    if page_name.startswith("Technical-Plugin-") and page_name not in (
        "Technical-Plugin-Index",
        "Technical-Plugin-Framework",
    ):
        return "technical_plugin"
    if page_name.startswith("Technical-"):
        return "technical"
    return "guide"


def markdown_metadata(page_name: str, text: str) -> dict[str, str]:
    """Metadata the page states about itself; nothing is inferred when the page is silent."""
    head = "".join(line for line, in_code in markdown_lines(text) if not in_code)[:3000]
    metadata = {"category": doc_category(page_name)}

    title = _H1.search(head)
    metadata["title"] = title.group(1).strip() if title else page_name

    for key, pattern in (
        ("audience", _AUDIENCE),
        ("review_date", _REVIEW_DATE),
        ("plugin_version", _PLUGIN_VERSION),
        ("code_ownership", _CODE_OWNERSHIP),
    ):
        match = pattern.search(head)
        if match:
            metadata[key] = match.group(1).strip()

    if metadata["category"] == "technical_plugin":
        metadata["plugin"] = page_name.removeprefix("Technical-Plugin-")

    return metadata


def absolutize_wiki_links(text: str) -> str:
    """Point relative wiki links at the public wiki, so excerpts carry citable URLs."""
    return _RELATIVE_WIKI_LINK.sub(lambda m: f"]({WIKI_BASE_URL}{m.group(1)})", text)


class DocumentLoader:
    """
    Loads documents using LlamaIndex readers.
    
    Supports PDF and Markdown files, extracting text content
    along with metadata including file path, file name, and page numbers.
    """
    
    def __init__(self) -> None:
        """Initialize the document loader."""
        pass
    
    def load_file(self, file_path: Path, root: Path | None = None) -> list[Document]:
        """
        Load a single file and return documents with metadata.

        Args:
            file_path: Path to the file (PDF or Markdown)
            root: Documents directory, to record the file path relative to it

        Returns:
            List of LlamaIndex Document objects
        """
        if not file_path.exists():
            logger.error(f"File not found: {file_path}")
            return []

        extension = file_path.suffix.lower()

        if extension == ".pdf":
            docs = self._load_pdf(file_path)
        elif extension in {".md", ".markdown"}:
            docs = self._load_markdown(file_path)
        else:
            logger.warning(f"Unsupported file type: {file_path}")
            return []

        relative_path = file_path.name
        if root is not None and file_path.resolve().is_relative_to(root.resolve()):
            relative_path = file_path.resolve().relative_to(root.resolve()).as_posix()
        for doc in docs:
            doc.metadata["relative_path"] = relative_path
        return docs
    
    def _load_pdf(self, file_path: Path) -> list[Document]:
        """
        Load a PDF file using pdfplumber (more tolerant with problematic PDFs).
        
        Args:
            file_path: Path to the PDF file
            
        Returns:
            List of Document objects (one per page)
        """
        try:
            import pdfplumber
            
            logger.info(f"Loading PDF: {file_path.name}")
            
            enriched_docs = []
            with pdfplumber.open(file_path) as pdf:
                total_pages = len(pdf.pages)
                
                for idx, page in enumerate(pdf.pages):
                    text = page.extract_text()
                    if text and text.strip():
                        doc = Document(
                            text=text,
                            metadata={
                                "file_path": str(file_path.absolute()),
                                "file_name": file_path.name,
                                "file_type": "pdf",
                                "page_number": idx + 1,
                                "total_pages": total_pages,
                                "title": file_path.stem,
                                "category": "pdf",
                            }
                        )
                        enriched_docs.append(doc)
            
            logger.info(f"Loaded {len(enriched_docs)} pages from {file_path.name}")
            return enriched_docs
            
        except Exception as e:
            logger.error(f"Error loading PDF {file_path}: {e}")
            return []
    
    def _load_markdown(self, file_path: Path) -> list[Document]:
        """
        Load a Markdown file.
        
        Args:
            file_path: Path to the Markdown file
            
        Returns:
            List containing a single Document object
        """
        try:
            logger.info(f"Loading Markdown: {file_path.name}")

            content = file_path.read_text(encoding="utf-8")

            # Generated pages start with a maintenance comment that is not documentation
            generated = content.startswith(GENERATED_MARKER)
            if generated:
                content = content.split("\n", 1)[1] if "\n" in content else ""

            if not content.strip():
                logger.warning(f"Empty markdown file: {file_path.name}")
                return []

            page_name = file_path.stem
            doc = Document(
                text=absolutize_wiki_links(content),
                metadata={
                    "file_path": str(file_path.absolute()),
                    "file_name": file_path.name,
                    "file_type": "markdown",
                    "page_number": 1,
                    "total_pages": 1,
                    "wiki_page": page_name,
                    "wiki_url": wiki_url(page_name),
                    "generated": generated,
                    **markdown_metadata(page_name, content),
                },
            )
            
            logger.info(f"Loaded markdown file: {file_path.name}")
            return [doc]
            
        except Exception as e:
            logger.error(f"Error loading Markdown {file_path}: {e}")
            return []
    
    def load_directory(
        self, 
        directory: Path, 
        recursive: bool = True
    ) -> dict[str, list[Document]]:
        """
        Load all supported files from a directory.
        
        Args:
            directory: Path to the directory containing documents
            recursive: Whether to search subdirectories
            
        Returns:
            Dictionary mapping file paths to their documents
        """
        if not directory.exists():
            logger.error(f"Directory not found: {directory}")
            return {}
        
        if not directory.is_dir():
            logger.error(f"Not a directory: {directory}")
            return {}
        
        # Find all supported files
        candidates = directory.rglob("*") if recursive else directory.glob("*")
        all_files = sorted(p for p in candidates if p.is_file() and is_indexable(p))

        logger.info(f"Found {len(all_files)} supported files in {directory}")
        
        results: dict[str, list[Document]] = {}
        for file_path in all_files:
            docs = self.load_file(file_path, root=directory)
            if docs:
                results[str(file_path)] = docs
        
        total_docs = sum(len(docs) for docs in results.values())
        logger.info(f"Loaded {total_docs} total documents from {len(results)} files")
        
        return results


# Backward compatibility alias
PDFDocumentLoader = DocumentLoader
