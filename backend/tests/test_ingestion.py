PLUGIN_PAGE = """<!-- Generated by technical/tools/build_reference.py; edit source. -->

# Technical: VideoThumbnails plugin

Generates seek-bar preview sprites using the Web Encoder.

Audience: developers, advanced administrators and AI-assisted diagnosis. [Plugin catalog](https://github.com/WWBN/AVideo/wiki/Technical-Plugin-Index).

## Source baseline

- Review date: 2026-10-29. Method: static source analysis.
- Code ownership: independently versioned plugin repository.
- Reported version: `6.0`.

## Behavior and operational checks

Worker attempts are limited to one per destination every 600 seconds.
"""


def saved_state(tmp_path: Path) -> tuple[dict, FAISSVectorStore]:
    """Manifest and index as a new process would read them from disk."""
    manifest = json.loads((tmp_path / "manifest.json").read_text(encoding="utf-8"))["documents"]
    store = FAISSVectorStore(index_path=tmp_path / "faiss", embeddings=KeywordEmbeddings())
    assert store.load()
    return manifest, store


def chunks_by_file(store: FAISSVectorStore) -> dict[str, list[str]]:
    result: dict[str, list[str]] = {}
    for doc in store._vectorstore.docstore._dict.values():
        result.setdefault(Path(doc.metadata["file_path"]).name, []).append(doc.page_content)
    return result


def assert_in_sync(manifest: dict, store: FAISSVectorStore) -> None:
    assert store.vector_count == sum(entry["chunk_count"] for entry in manifest.values())
    assert set(chunks_by_file(store)) == {Path(key).name for key in manifest}


def test_markdown_in_subfolders_is_indexed_with_wiki_page_name(make_pipeline, docs_dir, tmp_path):
    write(docs_dir / "Home.md", "# Home\n\nWelcome to AVideo.\n")
    write(docs_dir / "technical" / "plugins" / "Technical-Plugin-VideoThumbnails.md", PLUGIN_PAGE)
    write(docs_dir / "_Sidebar.md", "- [Home](Home)\n")
    make_pdf(docs_dir / "WebRTC to RTMP Plans.pdf", ["Free Plan 1 RTMP stream", "Pro Plan 10 RTMP streams"])

    stats = make_pipeline().run()

    assert stats["errors"] == []
    manifest, store = saved_state(tmp_path)
    assert sorted(Path(k).name for k in manifest) == [
        "Home.md",
        "Technical-Plugin-VideoThumbnails.md",
        "WebRTC to RTMP Plans.pdf",
    ]
    assert_in_sync(manifest, store)

    docs = list(store._vectorstore.docstore._dict.values())
    technical = [d for d in docs if d.metadata["file_name"] == "Technical-Plugin-VideoThumbnails.md"]
    meta = technical[0].metadata
    assert meta["relative_path"] == "technical/plugins/Technical-Plugin-VideoThumbnails.md"
    assert meta["wiki_url"] == "https://github.com/WWBN/AVideo/wiki/Technical-Plugin-VideoThumbnails"
    assert meta["category"] == "technical_plugin"
    assert meta["plugin"] == "VideoThumbnails"
    assert meta["plugin_version"] == "6.0"
    assert meta["review_date"] == "2026-10-29"
    assert meta["audience"].startswith("developers, advanced administrators")
    assert meta["generated"] is True
    assert not any("Generated by" in d.page_content for d in technical)

    pdf_pages = sorted(d.metadata["page_number"] for d in docs if d.metadata["file_type"] == "pdf")
    assert pdf_pages == [1, 2]
    assert all("wiki_url" not in d.metadata for d in docs if d.metadata["file_type"] == "pdf")


def test_new_changed_and_removed_documents(make_pipeline, docs_dir, tmp_path, embeddings):
    write(docs_dir / "A.md", "# A\n\nThe original alpha text.\n")
    write(docs_dir / "B.md", "# B\n\nBeta text that will be removed.\n")
    make_pipeline().run()

    write(docs_dir / "technical" / "C.md", "# C\n\nA new gamma page.\n")
    write(docs_dir / "A.md", "# A\n\nThe updated alpha text.\n")
    (docs_dir / "B.md").unlink()
    embedded_before = embeddings.embedded_texts

    stats = make_pipeline().run()

    assert stats["files_processed"] == 2
    assert stats["files_removed"] == 1
    assert embeddings.embedded_texts - embedded_before == 2  # only A and C were embedded again
    manifest, store = saved_state(tmp_path)
    assert_in_sync(manifest, store)
    contents = chunks_by_file(store)
    assert set(contents) == {"A.md", "C.md"}
    assert any("updated alpha" in c for c in contents["A.md"])
    assert not any("original alpha" in c for c in contents["A.md"])
    hits = store.similarity_search("Beta text that will be removed", k=5)
    assert all(h.metadata["file_name"] != "B.md" for h in hits)


def test_repeated_runs_do_not_duplicate(make_pipeline, docs_dir, tmp_path, embeddings):
    write(docs_dir / "A.md", "# A\n\n" + "Alpha paragraph.\n\n" * 200)
    write(docs_dir / "B.md", "# B\n\nBeta.\n")
    make_pipeline().run()
    manifest, store = saved_state(tmp_path)
    first_count = store.vector_count
    embedded = embeddings.embedded_texts

    second = make_pipeline().run()
    assert second["files_processed"] == 0
    assert embeddings.embedded_texts == embedded

    make_pipeline().run(rebuild=True)
    manifest, store = saved_state(tmp_path)
    assert store.vector_count == first_count
    assert_in_sync(manifest, store)


def test_change_removes_duplicates_left_by_older_builds(make_pipeline, docs_dir, tmp_path):
    """Older incremental runs appended a changed file's chunks without removing the old ones."""
    write(docs_dir / "A.md", "# A\n\nFirst version.\n")
    make_pipeline().run()
    _, store = saved_state(tmp_path)
    legacy = [
        Document(page_content=d.page_content, metadata=d.metadata)
        for d in store._vectorstore.docstore._dict.values()
    ]
    store._vectorstore.add_documents(legacy)  # duplicate with random ids, as the old code did
    assert store.save()

    write(docs_dir / "A.md", "# A\n\nSecond version.\n")
    make_pipeline().run()

    manifest, store = saved_state(tmp_path)
    assert_in_sync(manifest, store)
    assert chunks_by_file(store)["A.md"] == ["[A | A]\n# A\n\nSecond version."]


def test_failed_index_save_does_not_record_success(make_pipeline, docs_dir, tmp_path, monkeypatch):
    write(docs_dir / "A.md", "# A\n\nFirst version.\n")
    make_pipeline().run()
    manifest_before = (tmp_path / "manifest.json").read_text(encoding="utf-8")
    index_before = (tmp_path / "faiss" / "index.snapshot").read_bytes()

    write(docs_dir / "A.md", "# A\n\nSecond version.\n")
    write(docs_dir / "B.md", "# B\n\nNew page.\n")

    def broken_save(self):
        raise OSError("disk full")

    monkeypatch.setattr(FAISS, "serialize_to_bytes", broken_save)
    with pytest.raises(RuntimeError, match="could not be saved"):
        make_pipeline().run()
    monkeypatch.undo()

    assert (tmp_path / "manifest.json").read_text(encoding="utf-8") == manifest_before
    assert (tmp_path / "faiss" / "index.snapshot").read_bytes() == index_before
    assert not list((tmp_path / "faiss").glob(".saving-*"))

    # The next run retries the same files and ends consistent, without duplicates
    stats = make_pipeline().run()
    assert stats["files_processed"] == 2
    manifest, store = saved_state(tmp_path)
    assert_in_sync(manifest, store)
    assert not any("First version" in c for c in chunks_by_file(store)["A.md"])


