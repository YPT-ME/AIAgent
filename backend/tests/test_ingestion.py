def test_cli_reports_status_and_exits_with_error_on_failure(docs_dir, tmp_path, monkeypatch, capsys):
    """The command used by ingest.sh and the container entrypoint."""
    from src.ingestion import ingest, manifest, vectorstore

    monkeypatch.setattr(vectorstore, "get_embeddings", KeywordEmbeddings)
    monkeypatch.setattr(vectorstore, "_vectorstore", None)
    monkeypatch.setattr(manifest, "_manifest_manager", None)
    monkeypatch.setenv("FAISS_INDEX_PATH", str(tmp_path / "faiss"))
    monkeypatch.setenv("MANIFEST_PATH", str(tmp_path / "manifest.json"))
    write(docs_dir / "technical" / "Technical-Payments.md", "# Technical payments\n\nWallet.\n")

    def run_cli(*args: str) -> None:
        monkeypatch.setattr("sys.argv", ["rag-ingest", "--docs-dir", str(docs_dir), *args])
        monkeypatch.setattr(vectorstore, "_vectorstore", None)
        monkeypatch.setattr(manifest, "_manifest_manager", None)
        ingest.main()

    run_cli()
    run_cli("--status")
    output = capsys.readouterr().out
    assert "Files Processed: 1" in output
    assert "Indexed Documents:      1" in output

    write(docs_dir / "technical" / "Technical-Payments.md", "# Technical payments\n\nChanged.\n")
    monkeypatch.setattr(vectorstore.FAISSVectorStore, "save", lambda _self: False)
    with pytest.raises(SystemExit) as exit_info:
        run_cli()
    assert exit_info.value.code == 1


def test_chunks_of_files_missing_from_the_manifest_are_removed(make_pipeline, docs_dir, tmp_path):
    """Older builds could leave chunks in the index of files the manifest no longer lists."""
    write(docs_dir / "A.md", "# A\n\nAlpha.\n")
    write(docs_dir / "Orphan.md", "# Orphan\n\nOrphan text.\n")
    make_pipeline().run()
    manifest_file = tmp_path / "manifest.json"
    data = json.loads(manifest_file.read_text(encoding="utf-8"))
    data["documents"] = {k: v for k, v in data["documents"].items() if not k.endswith("Orphan.md")}
    manifest_file.write_text(json.dumps(data), encoding="utf-8")
    (docs_dir / "Orphan.md").unlink()

    write(docs_dir / "A.md", "# A\n\nAlpha changed.\n")
    make_pipeline().run()

    manifest, store = saved_state(tmp_path)
    assert_in_sync(manifest, store)
    assert "Orphan.md" not in chunks_by_file(store)


def test_unchanged_file_with_leftover_old_chunks_is_reindexed(make_pipeline, docs_dir, tmp_path, embeddings):
    write(docs_dir / "A.md", "# A\n\nCurrent version.\n")
    write(docs_dir / "B.md", "# B\n\nBeta.\n")
    make_pipeline().run()
    _, store = saved_state(tmp_path)
    a_path = str((docs_dir / "A.md").absolute())
    store._vectorstore.add_documents(
        [Document(page_content="Old version.", metadata={"file_path": a_path, "file_name": "A.md"})]
    )
    store._vectorstore.add_documents(
        [Document(page_content="Gone.", metadata={"file_path": "/old/Gone.md", "file_name": "Gone.md"})]
    )
    assert store.save()
    embedded = embeddings.embedded_texts

    stats = make_pipeline().run()

    assert stats["files_processed"] == 1  # only A; B is consistent and is not embedded again
    assert embeddings.embedded_texts - embedded == 1
    manifest, store = saved_state(tmp_path)
    assert_in_sync(manifest, store)
    assert chunks_by_file(store)["A.md"] == ["[A | A]\n# A\n\nCurrent version."]
